import { blankChecks } from './bridge-types'
import type { BridgeCheck, BridgeJob, CheckState } from './bridge-types'

// 廊桥许可示例数据：检查项逐项存盘，与机位台账（stand）、航班（flight）里的记录保持一致。
function checks(spec: { key: string; state: CheckState; remark?: string; at?: string; by?: string }[]): BridgeCheck[] {
  return blankChecks().map((item) => {
    const hit = spec.find((s) => s.key === item.key)
    return hit
      ? { ...item, state: hit.state, remark: hit.remark ?? '', checkedAt: hit.at ?? (hit.state === 'pending' ? '' : '2026-10-04 08:00'), checkedBy: hit.by ?? (hit.state === 'pending' ? '' : '张伟') }
      : item
  })
}

